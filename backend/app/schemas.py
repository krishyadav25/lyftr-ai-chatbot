from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field, field_validator


class ChatRequest(BaseModel):
    """POST /chat request payload."""

    session_id: str = Field(
        ...,
        description="Required, 1-128 chars, generated by the client. An unknown id starts a new session.",
    )
    message: str = Field(
        ...,
        description="Required, 1-4000 chars after trimming whitespace.",
    )
    system_prompt: Optional[str] = Field(
        default=None,
        description="Optional; overrides the default system prompt for this session.",
    )

    @field_validator("session_id")
    @classmethod
    def validate_session_id(cls, v: str) -> str:
        trimmed = v.strip() if v else ""
        if not trimmed or len(v) < 1 or len(v) > 128:
            raise ValueError("session_id must be between 1 and 128 characters")
        return v

    @field_validator("message")
    @classmethod
    def validate_message(cls, v: str) -> str:
        trimmed = v.strip()
        if not trimmed:
            raise ValueError("message must not be empty after trimming whitespace")
        if len(trimmed) > 4000:
            raise ValueError("message must not exceed 4000 characters after trimming whitespace")
        return trimmed


class AssistantMetadata(BaseModel):
    """Metadata included with assistant replies."""

    resolution_source: Literal["LIVE_INFERENCE", "LLM_CACHE"]
    model: str
    latency_ms: int
    input_tokens: int
    output_tokens: int
    key_id: Optional[str] = None
    fallback_attempts: int = 0


class ChatResponse(BaseModel):
    """POST /chat 200 response payload."""

    session_id: str
    reply: str
    metadata: AssistantMetadata


class SessionMessage(BaseModel):
    """Single message item in session history."""

    role: Literal["user", "assistant"]
    content: str
    metadata: Optional[Dict[str, Any]] = None


class SessionHistoryResponse(BaseModel):
    """GET /sessions/{session_id}/messages 200 response payload."""

    session_id: str
    messages: List[SessionMessage]


class HealthResponse(BaseModel):
    """GET /health 200 response payload."""

    status: str
    keys_configured: int
    cache_enabled: bool


class ErrorResponse(BaseModel):
    """Standard JSON error envelope."""

    detail: Any
